// Command apidocgen reads cmd/server's source and writes apidocs_gen.go: for
// every handler, the comment on the line that registers its route and the
// handler's own doc comment. The API reference (apidocs.go) uses them for
// endpoints that have no hand-written description.
//
//	go generate ./cmd/server
package main

import (
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

func main() {
	dir := "."
	if len(os.Args) > 1 {
		dir = os.Args[1]
	}
	fset := token.NewFileSet()
	files, _ := filepath.Glob(filepath.Join(dir, "*.go"))
	routeNotes := map[string]string{} // handler -> comment on its route line
	docs := map[string]string{}       // handler -> its doc comment
	for _, path := range files {
		if strings.HasSuffix(path, "_test.go") || strings.HasSuffix(path, "apidocs_gen.go") {
			continue
		}
		f, err := parser.ParseFile(fset, path, nil, parser.ParseComments)
		if err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		lineComment := map[int]string{}
		for _, cg := range f.Comments {
			for _, c := range cg.List {
				if strings.HasPrefix(c.Text, "//") {
					lineComment[fset.Position(c.Pos()).Line] = strings.TrimSpace(strings.TrimPrefix(c.Text, "//"))
				}
			}
		}
		ast.Inspect(f, func(n ast.Node) bool {
			switch x := n.(type) {
			case *ast.FuncDecl:
				if x.Recv != nil && x.Doc != nil {
					docs[x.Name.Name] = strings.TrimSpace(x.Doc.Text())
				}
			case *ast.CallExpr:
				sel, ok := x.Fun.(*ast.SelectorExpr)
				if !ok || len(x.Args) != 2 {
					return true
				}
				switch sel.Sel.Name {
				case "Get", "Post", "Put", "Patch", "Delete":
				default:
					return true
				}
				h := handlerName(x.Args[1])
				if h == "" {
					return true
				}
				if c := lineComment[fset.Position(x.End()).Line]; c != "" {
					if _, seen := routeNotes[h]; !seen {
						routeNotes[h] = c
					}
				}
			}
			return true
		})
	}
	var b strings.Builder
	b.WriteString("// Code generated by cmd/apidocgen; DO NOT EDIT.\n\npackage main\n\n")
	writeMap(&b, "genRouteNotes", routeNotes)
	writeMap(&b, "genHandlerDocs", docs)
	out, err := format.Source([]byte(b.String()))
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile(filepath.Join(dir, "apidocs_gen.go"), out, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

// handlerName: s.foo -> "foo"; s.foo("x") -> "foo".
func handlerName(e ast.Expr) string {
	if c, ok := e.(*ast.CallExpr); ok {
		e = c.Fun
	}
	if s, ok := e.(*ast.SelectorExpr); ok {
		if id, ok := s.X.(*ast.Ident); ok && id.Name == "s" {
			return s.Sel.Name
		}
	}
	return ""
}

func writeMap(b *strings.Builder, name string, m map[string]string) {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	fmt.Fprintf(b, "var %s = map[string]string{\n", name)
	for _, k := range keys {
		fmt.Fprintf(b, "\t%q: %q,\n", k, m[k])
	}
	b.WriteString("}\n\n")
}
